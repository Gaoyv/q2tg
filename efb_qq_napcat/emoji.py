def format_qq_face(data: dict[str, Any]) -> str:
    face_id = str(data.get("id", "?"))
    try:
        mapped = QQ_FACE_EMOJI.get(int(face_id))
    except (TypeError, ValueError):
        mapped = None
    if mapped:
        return mapped

    raw = data.get("raw")
    if isinstance(raw, dict):
        face_text = raw.get("faceText")
        if isinstance(face_text, str) and face_text.strip():
            return f"[{face_text.strip().lstrip('/')}]"
    return f"[QQ表情:{face_id}]"
